import assert from 'node:assert/strict';
import fs from 'node:fs';
import {ageFromDate,checkScheme} from '../public/js/scheme-rules.js';
const schemes=JSON.parse(fs.readFileSync(new URL('../database/fixtures/my-place-schemes.json',import.meta.url))).schemes;
const byId=id=>schemes.find(s=>s.id===id);
const profile={age:40,citizen:'yes',bank:'yes',autodebit:'yes',state:'9',land:'yes',kisan_exclusion:'no',other_pension:'no',family_income:46080,residence_type:'rural'};
assert.equal(checkScheme(byId('pmjjby'),profile).status,'potential');
assert.equal(checkScheme(byId('pmjjby'),{...profile,age:51}).status,'not_matched');
assert.equal(checkScheme(byId('pmsby'),{...profile,age:70}).status,'potential');
assert.equal(checkScheme(byId('pmsby'),{...profile,age:71}).status,'not_matched');
assert.equal(checkScheme(byId('pm-kisan'),{...profile,kisan_exclusion:''}).status,'needs_information');
assert.equal(checkScheme(byId('pm-kisan'),{...profile,kisan_exclusion:'yes'}).status,'not_matched');
assert.equal(checkScheme(byId('up-old-age'),{...profile,age:60}).status,'potential');
assert.equal(checkScheme(byId('up-old-age'),{...profile,age:60,family_income:46081}).status,'not_matched');
assert.equal(checkScheme(byId('up-old-age'),{...profile,age:60,state:'8'}).status,'not_matched');
assert.equal(checkScheme(byId('up-old-age'),{...profile,age:60,family_income:''}).status,'needs_information');
assert.equal(checkScheme(byId('up-old-age'),{...profile,age:60,family_income:0}).status,'potential');
assert.equal(ageFromDate('2008-10-28',new Date(2026,9,27)),17);
assert.equal(ageFromDate('2008-10-27',new Date(2026,9,27)),18);
assert.equal(ageFromDate('2000-02-31'),null);
assert.equal(ageFromDate('2099-01-01'),null);
console.log('15 scheme eligibility and age boundary checks passed.');

const today=new Date(2026,9,28), sample={scope:'IN',status:'listed',checked_on:'2026-10-28',rules:[{field:'age',op:'gte',value:18}]};
assert.equal(checkScheme({...sample,rules:[]},profile,today).status,'needs_verification');
assert.equal(checkScheme({...sample,rules_verified:false},profile,today).status,'needs_verification');
assert.equal(checkScheme({...sample,status:'unknown'},profile,today).status,'needs_verification');
for(const status of ['closed','inactive'])assert.equal(checkScheme({...sample,status},profile,today).status,'unavailable');
assert.equal(checkScheme({...sample,valid_until:'2026-10-27'},profile,today).status,'unavailable');
assert.equal(checkScheme({...sample,valid_from:'2026-10-29'},profile,today).status,'unavailable');
assert.equal(checkScheme({...sample,valid_until:'2026-10-28'},profile,today).status,'potential');
assert.equal(checkScheme({...sample,valid_until:'2026-02-31'},profile,today).status,'needs_verification');
assert.equal(checkScheme({...sample,checked_on:'2026-01-01'},profile,today).status,'needs_verification');
assert.equal(checkScheme({...sample,checked_on:'2099-01-01'},profile,today).status,'needs_verification');
assert.equal(checkScheme({...sample,scope:'8'},profile,today).status,'not_matched');
assert.equal(checkScheme({...sample,rules:[{field:'age',op:'unknown',value:18}]},profile,today).status,'needs_verification');
for(const value of [null,'',[],true])assert.equal(checkScheme({...sample,rules:[{field:'age',op:'gte',value}]},profile,today).status,'needs_verification');
const occupation={...sample,rules:[{field:'occupation',op:'in',value:['farmer','student']}]};
assert.equal(checkScheme(occupation,{...profile,occupation:'farmer'},today).status,'potential');
assert.equal(checkScheme(occupation,{...profile,occupation:''},today).status,'needs_information');
assert.equal(checkScheme(occupation,{...profile,occupation:'retired'},today).status,'not_matched');
console.log('20 lifecycle, source-verification, scope and broader-field checks passed.');
